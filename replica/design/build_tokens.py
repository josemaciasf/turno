#!/usr/bin/env python3
"""Generate tokens.css, tailwind.preset.js and theme.ts from tokens.json.

tokens.json is the single source; re-run this after every palette change
(including /replica-brand):

    python3 replica/design/build_tokens.py
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
HEADER = "Generated by build_tokens.py from tokens.json. Do not edit by hand."


def load():
    with open(os.path.join(HERE, "tokens.json")) as f:
        return json.load(f)


def css(t):
    lines = ["/* %s */" % HEADER, ":root {"]
    for name, value in t["color"].items():
        lines.append("  --color-%s: %s;" % (name, value))
    for name, spec in t["type"].items():
        lines.append("  --text-%s: %dpx;" % (name, spec["size"]))
        lines.append("  --leading-%s: %dpx;" % (name, spec["line"]))
        lines.append("  --weight-%s: %d;" % (name, spec["weight"]))
    for i, value in enumerate(t["space"]):
        lines.append("  --space-%d: %dpx;" % (i, value))
    for name, value in t["radius"].items():
        lines.append("  --radius-%s: %dpx;" % (name, value))
    for name, value in t["shadow"].items():
        lines.append("  --shadow-%s: %s;" % (name, value))
    for name, value in t["motion"].items():
        lines.append("  --motion-%s: %s;" % (name, value))
    for name, value in t["layout"].items():
        if isinstance(value, (int, float)):
            lines.append("  --layout-%s: %dpx;" % (name, value))
    lines.append("  --font-sans: %s;" % t["font"]["sans"])
    lines.append("  --font-mono: %s;" % t["font"]["mono"])
    lines.append("}")
    return "\n".join(lines) + "\n"


def tailwind(t):
    colors = {name: "var(--color-%s)" % name for name in t["color"]}
    font_size = {
        name: ["var(--text-%s)" % name,
               {"lineHeight": "var(--leading-%s)" % name, "fontWeight": "var(--weight-%s)" % name}]
        for name in t["type"]
    }
    preset = {
        "theme": {
            "colors": dict(colors, transparent="transparent", current="currentColor"),
            "fontFamily": {"sans": ["var(--font-sans)"], "mono": ["var(--font-mono)"]},
            "fontSize": font_size,
            "borderRadius": dict({name: "var(--radius-%s)" % name for name in t["radius"]}, none="0"),
            "boxShadow": dict({name: "var(--shadow-%s)" % name for name in t["shadow"]}, none="none"),
            "screens": {name: "%dpx" % px for name, px in t["layout"]["breakpoints"].items()},
            "extend": {
                # Keyed like Tailwind (px / 4) so p-4 = 16px; the token scale's
                # values are a subset of Tailwind's own, so sizing like h-10 still works.
                "spacing": {str(v // 4): "var(--space-%d)" % i for i, v in enumerate(t["space"])},
                "transitionDuration": {"fast": t["motion"]["fast"], "base": t["motion"]["base"]},
                "transitionTimingFunction": {"brand": t["motion"]["ease"]},
                "width": {"sidebar": "var(--layout-sidebar)"},
                "height": {"header": "var(--layout-header)"},
                "maxWidth": {"content": "var(--layout-content-max)"},
                "minHeight": {"tap": "var(--layout-tap-target)"},
            },
        }
    }
    return "// %s\n// Use: presets: [require('./tailwind.preset.js')] and import tokens.css once.\nmodule.exports = %s;\n" % (
        HEADER, json.dumps(preset, indent=2))


def expo(t):
    theme = {
        "color": t["color"],
        "type": {name: {"fontSize": s["size"], "lineHeight": s["line"], "fontWeight": str(s["weight"])}
                 for name, s in t["type"].items()},
        "space": t["space"],
        "radius": t["radius"],
        "layout": {k: v for k, v in t["layout"].items() if not isinstance(v, dict)},
    }
    return "// %s\nexport const theme = %s as const;\nexport type Theme = typeof theme;\n" % (
        HEADER, json.dumps(theme, indent=2))


def main():
    t = load()
    for name, render in (("tokens.css", css), ("tailwind.preset.js", tailwind), ("theme.ts", expo)):
        with open(os.path.join(HERE, name), "w") as f:
            f.write(render(t))
        print("wrote", name)


if __name__ == "__main__":
    main()
